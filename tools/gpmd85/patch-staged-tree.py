#!/usr/bin/env python3
"""Transform the staged GPMD85Emulator machine tree so it builds as part of ours.

Run by cmake/StageGPMD85.cmake against core/gpmd85-generated after the copy:

    patch-staged-tree.py <staged-root>

Jobs:

  1. Generate `config.h`. GPMD85Emulator's CMakeLists configures it from
     config.h.in; we do not run that CMakeLists (it requires SDL2, OpenGL and
     the Dear ImGui submodule), so the handful of values the machine sources
     use are written here. Everything else in it is resolved by the
     preprocessor, so one generated file serves Linux, macOS and Windows.

  2. The debugger's hooks into the 8080 (a bus tap on memory and I/O, a
     side-effect-free peek). See the DEBUG section below.

Every transform is an (anchor, replacement) pair applied idempotently: the
replacement is tested first, and a missing anchor fails the build instead of
silently leaving a hook out.

Everything is written back as UTF-8 with surrogateescape and no newline
translation: Python on Windows otherwise decodes these sources as cp1252 and
rewrites every LF as CRLF on the way out.
"""

import sys
from pathlib import Path


def read(p: Path) -> str:
    return p.read_text(encoding="utf-8", errors="surrogateescape")


def write(p: Path, text: str) -> None:
    with p.open("w", encoding="utf-8", errors="surrogateescape", newline="") as f:
        f.write(text)


def fail(msg: str) -> None:
    sys.exit(f"patch-staged-tree.py: {msg}")


def patch(root: Path, rel: str, transforms) -> None:
    """Apply (anchor, replacement) pairs to root/rel, idempotently."""
    p = root / rel
    if not p.exists():
        fail(f"{rel} not found in the staged tree")
    text = read(p)
    for anchor, replacement in transforms:
        if replacement in text:
            continue
        if anchor not in text:
            fail(f"{rel}: anchor not found:\n{anchor}")
        text = text.replace(anchor, replacement, 1)
    write(p, text)


CONFIG_H = """\
/* Generated by tools/gpmd85/patch-staged-tree.py -- the values
 * GPMD85Emulator's CMakeLists would configure into config.h, for the machine
 * sources fujinet-go-pmd85-desktop builds. Not the upstream application. */
#ifndef GPMD85_STAGED_CONFIG_H
#define GPMD85_STAGED_CONFIG_H

#if defined(__has_include)
#  if __has_include(<filesystem>)
#    define HAVE_STD_FILESYSTEM 1
#  else
#    define HAVE_STD_EXPERIMENTAL_FILESYSTEM 1
#  endif
#else
#  define HAVE_STD_FILESYSTEM 1
#endif

#define PACKAGE "gpmd85emu"
#define PACKAGE_BUGREPORT "martin@borik.net"
#define PACKAGE_NAME "GPMD85emulator"
#define PACKAGE_STRING "GPMD85emulator (fujinet-go-pmd85-desktop)"
#define PACKAGE_TARNAME "fujinet-go-pmd85"
#define PACKAGE_URL "https://github.com/mborik/GPMD85Emulator"
#define PACKAGE_VERSION "staged"
#define PACKAGE_YEAR "2026"
#define VERSION "staged"
#define CONFIGURATION_VERSION "9"

#if defined(__BYTE_ORDER__) && __BYTE_ORDER__ == __ORDER_BIG_ENDIAN__
#  define WORDS_BIGENDIAN 1
#endif

/* upstream's debug()/trace output goes to stdout on every model change and
 * MegaModule page switch; the desktop app keeps stdout quiet */
#ifndef NOTRACEMSG
#  define NOTRACEMSG 1
#endif

#endif
"""


def main() -> None:
    if len(sys.argv) != 2:
        fail("usage: patch-staged-tree.py <staged-root>")
    root = Path(sys.argv[1])
    if not (root / "src" / "ChipCpu8080.cpp").exists():
        fail(f"{root} does not look like a staged GPMD85Emulator tree")

    write(root / "config.h", CONFIG_H)


if __name__ == "__main__":
    main()
