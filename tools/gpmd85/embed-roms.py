#!/usr/bin/env python3
"""Generate a C file embedding the PMD 85 firmware images into the binaries.

Usage: embed-roms.py <out.c> <image>...

Every image keeps its exact filename: the session materialises the table into
the user's ROM directory on first start (never overwriting a file already
there, so a user's own copy always wins) and the machine is pointed at files
in that directory by name -- the same scheme as the CoCo app, and the same
names GPMD85Emulator's own configuration uses.

The images are the GPMD85Emulator rom/ set (system monitors for every model
and the stock ROM-module contents) plus the FujiNet CONFIG loader module. All
of them are embedded in every build; see COMPLIANCE.md for their provenance.

The generated file lives in the build tree only.
"""

import sys
from pathlib import Path

MAX_IMAGE = 64 * 1024  # monitors are <= 16 KB, ROM modules <= 32 KB


def emit_array(out, ident: str, data: bytes) -> None:
    out.write(f"static const unsigned char {ident}[] = {{\n")
    for i in range(0, len(data), 16):
        row = ", ".join(f"0x{b:02x}" for b in data[i:i + 16])
        out.write(f"    {row},\n")
    out.write("};\n\n")


def ident_for(name: str) -> str:
    return "rom_" + "".join(c if c.isalnum() else "_" for c in name)


def main() -> int:
    args = sys.argv[1:]
    if len(args) < 2:
        sys.exit(__doc__)
    out_path = Path(args[0])
    images = []
    seen = set()
    for a in args[1:]:
        p = Path(a)
        data = p.read_bytes()
        # A truncated download or a stray file is a build error, not a machine
        # that half-boots. System monitors are whole EPROMs (upstream's
        # rom/README.md: "sizes are in multiples of kilobytes"); a ROM-module
        # image is padded with FFh by the module itself, so any length goes.
        if not data or len(data) > MAX_IMAGE:
            sys.exit(f"embed-roms.py: {p} is {len(data)} bytes; expected "
                     f"1 byte to {MAX_IMAGE // 1024} KB")
        if p.suffix.lower() == ".rom" and len(data) % 1024:
            sys.exit(f"embed-roms.py: {p} is {len(data)} bytes; a monitor "
                     f"ROM is a whole number of KB")
        if p.name in seen:
            sys.exit(f"embed-roms.py: duplicate image name {p.name}")
        seen.add(p.name)
        images.append((p.name, data))
    images.sort()

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8", newline="") as out:
        out.write("/* Generated by tools/gpmd85/embed-roms.py -- do not edit.\n"
                  " * See COMPLIANCE.md for the provenance of these images. */\n\n")
        out.write('#include "roms_embedded.h"\n\n')
        for name, data in images:
            emit_array(out, ident_for(name), data)
        out.write("const pmd85_embedded_rom pmd85_embedded_roms[] = {\n")
        for name, data in images:
            ident = ident_for(name)
            out.write(f'    {{ "{name}", {ident}, sizeof {ident} }},\n')
        out.write("};\n\n")
        out.write(f"const int pmd85_embedded_rom_count = {len(images)};\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
